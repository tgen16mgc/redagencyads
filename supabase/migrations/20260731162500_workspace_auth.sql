create or replace function public.request_workspace_access(
  p_email text,
  p_full_name text default null,
  p_note text default null
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  normalized_email text := lower(trim(p_email));
  target_workspace_id uuid;
  existing_request_id uuid;
  created_request_id uuid;
begin
  if normalized_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
    or char_length(normalized_email) > 320 then
    raise exception 'A valid work email is required.' using errcode = '22023';
  end if;

  if p_full_name is not null and char_length(trim(p_full_name)) > 120 then
    raise exception 'Full name is too long.' using errcode = '22023';
  end if;

  if p_note is not null and char_length(trim(p_note)) > 1000 then
    raise exception 'Request note is too long.' using errcode = '22023';
  end if;

  select id into target_workspace_id
  from public.workspaces
  where slug = 'decision-workspace';

  if target_workspace_id is null then
    raise exception 'Workspace is not configured.';
  end if;

  select id into existing_request_id
  from public.workspace_access_requests
  where workspace_id = target_workspace_id
    and email = normalized_email
    and status = 'pending'
    and requested_at > now() - interval '24 hours'
  order by requested_at desc
  limit 1;

  if existing_request_id is not null then
    return existing_request_id;
  end if;

  insert into public.workspace_access_requests (workspace_id, email, full_name, note)
  values (
    target_workspace_id,
    normalized_email,
    nullif(trim(coalesce(p_full_name, '')), ''),
    nullif(trim(coalesce(p_note, '')), '')
  )
  returning id into created_request_id;

  return created_request_id;
end;
$$;

revoke all on function public.request_workspace_access(text, text, text) from public;
grant execute on function public.request_workspace_access(text, text, text) to anon, authenticated;

create or replace function public.record_workspace_login(
  p_provider text default 'unknown',
  p_user_agent text default null
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := (select auth.uid());
  current_email text;
  current_workspace_id uuid;
  created_event_id bigint;
begin
  if current_user_id is null then
    raise exception 'Authentication is required.' using errcode = '42501';
  end if;

  select email into current_email from auth.users where id = current_user_id;
  select workspace_id into current_workspace_id
  from public.workspace_members
  where user_id = current_user_id and status = 'active'
  order by created_at
  limit 1;

  if current_workspace_id is null then
    raise exception 'Workspace access is not approved.' using errcode = '42501';
  end if;

  insert into public.workspace_login_events (workspace_id, user_id, email, provider, user_agent)
  values (
    current_workspace_id,
    current_user_id,
    lower(current_email),
    case when p_provider in ('email', 'google') then p_provider else 'unknown' end,
    left(nullif(trim(coalesce(p_user_agent, '')), ''), 500)
  )
  returning id into created_event_id;

  return created_event_id;
end;
$$;

revoke all on function public.record_workspace_login(text, text) from public;
grant execute on function public.record_workspace_login(text, text) to authenticated;

create or replace function public.handle_workspace_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  pending_invite public.workspace_invites%rowtype;
  resolved_name text;
begin
  if new.email is null then
    return new;
  end if;

  select * into pending_invite
  from public.workspace_invites
  where email = lower(new.email)
    and accepted_at is null
  order by created_at
  limit 1;

  if pending_invite.id is null then
    return new;
  end if;

  resolved_name := coalesce(
    nullif(trim(pending_invite.full_name), ''),
    nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''),
    nullif(trim(new.raw_user_meta_data ->> 'name'), ''),
    split_part(new.email, '@', 1)
  );

  insert into public.workspace_members (workspace_id, user_id, email, full_name, role, status)
  values (pending_invite.workspace_id, new.id, lower(new.email), resolved_name, pending_invite.role, 'active')
  on conflict (workspace_id, user_id) do update
  set email = excluded.email,
      full_name = excluded.full_name,
      role = excluded.role,
      status = 'active',
      updated_at = now();

  update public.workspace_invites
  set accepted_at = coalesce(accepted_at, now())
  where id = pending_invite.id;

  return new;
end;
$$;

drop trigger if exists on_auth_user_workspace_invite on auth.users;
create trigger on_auth_user_workspace_invite
after insert or update of email, raw_user_meta_data on auth.users
for each row execute function public.handle_workspace_auth_user();

