create table if not exists public.workspaces (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug = lower(slug)),
  name text not null check (char_length(name) between 2 and 120),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.workspace_invites (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  email text not null check (email = lower(email) and char_length(email) between 3 and 320),
  full_name text,
  role text not null default 'viewer' check (role in ('owner', 'admin', 'analyst', 'viewer')),
  accepted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists workspace_invites_workspace_email_key
  on public.workspace_invites (workspace_id, lower(email));

create table if not exists public.workspace_members (
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  email text not null check (email = lower(email) and char_length(email) between 3 and 320),
  full_name text not null check (char_length(full_name) between 1 and 120),
  role text not null default 'viewer' check (role in ('owner', 'admin', 'analyst', 'viewer')),
  status text not null default 'active' check (status in ('active', 'suspended')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (workspace_id, user_id)
);

create unique index if not exists workspace_members_workspace_email_key
  on public.workspace_members (workspace_id, lower(email));

create table if not exists public.workspace_access_requests (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  email text not null check (email = lower(email) and char_length(email) between 3 and 320),
  full_name text,
  note text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  requested_at timestamptz not null default now(),
  handled_at timestamptz,
  handled_by uuid references auth.users(id) on delete set null
);

create index if not exists workspace_access_requests_status_requested_at_idx
  on public.workspace_access_requests (workspace_id, status, requested_at desc);

create table if not exists public.workspace_login_events (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  email text not null,
  provider text not null check (provider in ('email', 'google', 'unknown')),
  user_agent text,
  signed_in_at timestamptz not null default now()
);

create index if not exists workspace_login_events_user_time_idx
  on public.workspace_login_events (user_id, signed_in_at desc);

